type WordLanguage = keyof typeof words;

/**
 * Builds a shuffled sequence without duplicate words inside a cycle. Battle
 * used to select every word independently, so the same short word could occur
 * several times in one screenful. Each new cycle is shuffled again, keeping
 * attempts varied while avoiding immediate repeats at the cycle boundary.
 */
export function createWordSequence(
  language: string,
  count: number,
  random: () => number = Math.random,
): string[] {
  const selected = words[language as WordLanguage] ?? words.en;
  const uniqueWords = [...new Set(selected)];
  if (count <= 0 || uniqueWords.length === 0) return [];

  const sequence: string[] = [];
  let previous: string | undefined;

  while (sequence.length < count) {
    const batch = [...uniqueWords];
    for (let i = batch.length - 1; i > 0; i -= 1) {
      const j = Math.floor(random() * (i + 1));
      [batch[i], batch[j]] = [batch[j], batch[i]];
    }

    if (previous !== undefined && batch.length > 1 && batch[0] === previous) {
      const swapIndex = batch.findIndex((word) => word !== previous);
      [batch[0], batch[swapIndex]] = [batch[swapIndex], batch[0]];
    }

    sequence.push(...batch);
    previous = sequence[sequence.length - 1];
  }

  return sequence.slice(0, count);
}

const BATTLE_CHUNK_SIZE = 50;

function getBattleChunkSignatures(words: string[]): string[] {
  const chunkSize = Math.min(BATTLE_CHUNK_SIZE, words.length);
  if (chunkSize === 0) return [];

  const signatures: string[] = [];
  for (let start = 0; start < words.length; start += chunkSize) {
    signatures.push(words.slice(start, start + chunkSize).join("\u0000"));
  }
  return signatures;
}

function isNewBattleRound(words: string[], usedChunks: Set<string>): boolean {
  const signatures = getBattleChunkSignatures(words);
  const uniqueChunks = new Set(signatures);
  return uniqueChunks.size === signatures.length && signatures.every((signature) => !usedChunks.has(signature));
}

function createSeededRandom(seed: number): () => number {
  let state = seed >>> 0;
  return () => {
    state += 0x6D2B79F5;
    let value = state;
    value = Math.imul(value ^ (value >>> 15), value | 1);
    value ^= value + Math.imul(value ^ (value >>> 7), value | 61);
    return ((value ^ (value >>> 14)) >>> 0) / 4_294_967_296;
  };
}

/**
 * Builds a battle text source round by round. A battle must not simply reveal
 * consecutive slices from one large shuffle: that makes later attempts feel
 * like the same text continuing. Every round receives a fresh order, and no
 * 50-word block is reused anywhere else in that battle.
 */
export function createBattleWordSequence(
  language: string,
  roundCount: number,
  wordsPerRound: number,
  random: () => number = Math.random,
): string[] {
  if (roundCount <= 0 || wordsPerRound <= 0) return [];

  const usedChunks = new Set<string>();
  const rounds: string[][] = [];

  for (let roundIndex = 0; roundIndex < roundCount; roundIndex += 1) {
    let round = createWordSequence(language, wordsPerRound, random);
    let attempts = 0;

    // A normal random shuffle passes on the first try. The retry and rotation
    // also make the "never the same order" rule hold with deterministic or
    // unlucky random sources.
    while (!isNewBattleRound(round, usedChunks) && attempts < 8) {
      round = createWordSequence(language, wordsPerRound, random);
      attempts += 1;
    }

    if (!isNewBattleRound(round, usedChunks)) {
      for (let fallback = 1; fallback <= 16; fallback += 1) {
        const seededRound = createWordSequence(
          language,
          wordsPerRound,
          createSeededRandom((roundIndex + 1) * 1_000 + fallback),
        );
        if (isNewBattleRound(seededRound, usedChunks)) {
          round = seededRound;
          break;
        }
      }
    }

    if (!isNewBattleRound(round, usedChunks) && round.length > 1) {
      for (let offset = 1; offset < round.length; offset += 1) {
        const rotated = [...round.slice(offset), ...round.slice(0, offset)];
        if (isNewBattleRound(rotated, usedChunks)) {
          round = rotated;
          break;
        }
      }
    }

    for (const signature of getBattleChunkSignatures(round)) {
      usedChunks.add(signature);
    }
    rounds.push(round);
  }

  return rounds.flat();
}
